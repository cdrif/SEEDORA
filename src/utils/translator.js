const I18nManager = {
    getCurrentLang() {
        return localStorage.getItem('seedora_user_lang') || 'en';
    },

    setLang(lang) {
        localStorage.setItem('seedora_user_lang', lang);
        this.translatePage();
    },

    translatePage() {
        const lang = this.getCurrentLang();
        const dict = translations[lang] || translations['en'];

        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (dict[key]) {
                el.textContent = dict[key];
            }
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (dict[key]) {
                el.placeholder = dict[key];
            }
        });

        const selector = document.getElementById('global-lang-selector');
        if (selector) {
            selector.value = lang;
        }
    },

    init() {
        document.addEventListener('DOMContentLoaded', () => {
            const selector = document.getElementById('global-lang-selector');
            if (selector) {
                // Populate the top 10 most spoken languages globally with country flag symbols
                selector.innerHTML = `
                    <option value="en">🇬🇧 English</option>
                    <option value="zh">🇨🇳 中文 (Chinese)</option>
                    <option value="es">🇪🇸 Español (Spanish)</option>
                    <option value="hi">🇮🇳 हिन्दी (Hindi)</option>
                    <option value="ar">🇸🇦 العربية (Arabic)</option>
                    <option value="pt">🇧🇷 Português (Portuguese)</option>
                    <option value="bn">🇧🇩 বাংলা (Bengali)</option>
                    <option value="ru">🇷🇺 Русский (Russian)</option>
                    <option value="ja">🇯🇵 日本語 (Japanese)</option>
                    <option value="pa">🇮🇳 ਪੰਜਾਬੀ (Punjabi)</option>
                `;
                selector.value = this.getCurrentLang();
                selector.addEventListener('change', (e) => {
                    this.setLang(e.target.value);
                });
            }
            this.translatePage();
        });
    }
};

window.i18n = I18nManager;
I18nManager.init();